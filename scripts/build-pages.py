def variant_path(src: str, *, width: int | None = None, webp: bool = False) -> str:
    p = Path(src)
    stem = p.stem if width is None else f"{p.stem}-{width}"
    suffix = ".webp" if webp else p.suffix
    return str(p.with_name(stem + suffix)).replace("\\", "/")


def existing(rel: str) -> bool:
    return (ROOT / rel).is_file()


@lru_cache(maxsize=None)
def image_width(rel: str) -> int | None:
    """Real pixel width of a master image (for the `w` srcset descriptor)."""
    path = ROOT / rel
    if not path.is_file():
        return None
    try:
        from PIL import Image

        with Image.open(path) as img:
            return img.size[0]
    except Exception:
        return None


def image_srcset(src: str, *, prefix: str = "", webp: bool = False) -> str | None:
    """srcset with every generated width variant plus the full-size master."""
    entries = []
    for w in VARIANT_WIDTHS:
        variant = variant_path(src, width=w, webp=webp)
        if existing(variant):
            entries.append(f"{prefix}{variant} {w}w")
    full = variant_path(src, webp=webp)
    full_width = image_width(src)
    if existing(full) and full_width:
        entries.append(f"{prefix}{full} {full_width}w")
    return ", ".join(entries) if entries else None


def picture_html(
    src: str,
    alt: str,
    *,
    prefix: str = "",
    css_class: str = "",
    width: int = 800,
    height: int = 600,
    sizes: str = "100vw",
    lazy: bool = True,
    high_priority: bool = False,
) -> str:
    """<picture> with webp + narrow variants when they exist on disk."""
    perf = 'decoding="async"'
    if high_priority:
        perf += ' fetchpriority="high"'
    elif lazy:
        perf += ' loading="lazy" fetchpriority="low"'
    cls = f' class="{esc(css_class)}"' if css_class else ""

    webp_set = image_srcset(src, prefix=prefix, webp=True)
    jpg_set = image_srcset(src, prefix=prefix, webp=False)

    sources = ""
    if webp_set:
        sources += f'<source type="image/webp" srcset="{esc(webp_set)}" sizes="{esc(sizes)}" />'
    img_srcset = f' srcset="{esc(jpg_set)}" sizes="{esc(sizes)}"' if jpg_set and ", " in jpg_set else ""
    img = (
        f'<img{cls} src="{esc(prefix + src)}"{img_srcset} alt="{esc(alt)}" '
        f'width="{width}" height="{height}" {perf} />'
    )
    if sources:
        return f"<picture>{sources}{img}</picture>"
    return img


