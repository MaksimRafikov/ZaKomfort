def main() -> int:
    site = load_site()
    cases = load_cases()
    tips = load_tips()

    # 1. Generated JS (data + config) — must exist before hashing versions.
    DATA_JS.write_text(build_data_js(cases), encoding="utf-8", newline="\n")
    print(f"generated: js/data.js ({len(cases)} cases)")
    CONFIG_JS.write_text(build_config_js(site), encoding="utf-8", newline="\n")
    print("generated: js/config.js")

    versions = asset_versions()

    # 2. Static case pages.
    known_ids = {c["id"] for c in cases}
    PAGES_DIR.mkdir(exist_ok=True)
    for stale in PAGES_DIR.iterdir():
        if stale.is_dir() and stale.name not in known_ids:
            shutil.rmtree(stale)
            print(f"removed stale page: cases/{stale.name}/")
    for c in cases:
        page_dir = PAGES_DIR / c["id"]
        page_dir.mkdir(parents=True, exist_ok=True)
        (page_dir / "index.html").write_text(
            build_case_page(site, c, versions), encoding="utf-8", newline="\n"
        )
        print(f'generated: cases/{c["id"]}/index.html')

    # 3. Static tip pages.
    known_tip_ids = {t["id"] for t in tips}
    TIPS_PAGES_DIR.mkdir(exist_ok=True)
    for stale in TIPS_PAGES_DIR.iterdir():
        if stale.is_dir() and stale.name not in known_tip_ids:
            shutil.rmtree(stale)
            print(f"removed stale page: tips/{stale.name}/")
    for tip in tips:
        page_dir = TIPS_PAGES_DIR / tip["id"]
        page_dir.mkdir(parents=True, exist_ok=True)
        (page_dir / "index.html").write_text(
            build_tip_page(site, tip, tips, versions), encoding="utf-8", newline="\n"
        )
    print(f"generated: tips/<slug>/index.html ({len(tips)} tips)")

    # 4. sitemap.xml
    SITEMAP.write_text(build_sitemap(site, cases, tips), encoding="utf-8", newline="\n")
    print("generated: sitemap.xml")

    # 5. Refresh ?v= versions and homepage JSON-LD in hand-written pages.
    for name in VERSIONED_HTML:
        path = ROOT / name
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8")
        updated = apply_versions(text, versions)
        if name == "index.html":
            updated = inject_home_jsonld(updated, site, cases)
        if updated != text:
            path.write_text(updated, encoding="utf-8", newline="\n")
            print(f"updated: {name}")

    print("BUILD_OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
