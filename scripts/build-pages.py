def build_sitemap(site: dict, cases: list[dict], tips: list[dict]) -> str:
    def entry(loc: str, lastmod: str, priority: str) -> str:
        return (
            "  <url>\n"
            f"    <loc>{esc(loc)}</loc>\n"
            f"    <lastmod>{lastmod}</lastmod>\n"
            f"    <priority>{priority}</priority>\n"
            "  </url>"
        )

    rows = [
        entry(abs_url(site, ""), file_date(ROOT / "index.html"), "1.0"),
        entry(abs_url(site, "tips.html"), file_date(ROOT / "tips.html"), "0.7"),
    ]
    for c in cases:
        rows.append(
            entry(
                case_url(site, c["id"]),
                file_date(CASES_DIR / f'{c["id"]}.json'),
                "0.8",
            )
        )
    for tip in tips:
        rows.append(entry(tip_url(site, tip["id"]), tip_asset_date(tip), "0.6"))
    body = "\n".join(rows)
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        f"{body}\n"
        "</urlset>\n"
    )


