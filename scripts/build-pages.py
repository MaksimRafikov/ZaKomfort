def esc(value: object) -> str:
    return html.escape(str(value if value is not None else ""), quote=True)


def load_site() -> dict:
    return json.loads((CONTENT_DIR / "site.json").read_text(encoding="utf-8"))


def load_cases() -> list[dict]:
    cases = []
    for path in sorted(CASES_DIR.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        if data.get("id") != path.stem:
            raise SystemExit(f"Case id mismatch: {path.name} has id={data.get('id')!r}")
        cases.append(data)
    cases.sort(key=lambda c: (c.get("order", 10_000), c["id"]))
    return cases


def load_tips() -> list[dict]:
    """EXPERT_TIPS from js/tips-data.js (generated by scripts/process-videos.py)."""
    if not TIPS_DATA_JS.is_file():
        return []
    text = TIPS_DATA_JS.read_text(encoding="utf-8")
    match = re.search(r"const EXPERT_TIPS = (\[.*?\]);", text, re.DOTALL)
    if not match:
        raise SystemExit("js/tips-data.js: EXPERT_TIPS array not found")
    return json.loads(match.group(1))


