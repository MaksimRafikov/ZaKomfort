# Cache-bust versions + JSON-LD injection in the hand-written root pages
# --------------------------------------------------------------------------

def asset_versions() -> dict[str, str]:
    versions: dict[str, str] = {}
    for rel_dir, pattern in (("css", "*.css"), ("js", "*.js")):
        for path in sorted((ROOT / rel_dir).glob(pattern)):
            digest = hashlib.md5(path.read_bytes()).hexdigest()[:10]
            versions[f"{rel_dir}/{path.name}"] = digest
    return versions


# Matches css/js references with or without an existing ?v=; the version is
# (re)computed from file content, so hand-editing ?v= is never needed.
VERSION_REF_RE = re.compile(
    r'(href|src)="((?:\.\./)*/?(?:css|js)/[\w./-]+)(?:\?v=[^"]*)?"'
)


def apply_versions(text: str, versions: dict[str, str]) -> str:
    def repl(m: re.Match) -> str:
        attr, path = m.group(1), m.group(2)
        rel = re.sub(r"^(\.\./)*/?", "", path)
        version = versions.get(rel)
        if not version:
            return m.group(0)
        return f'{attr}="{path}?v={version}"'

    return VERSION_REF_RE.sub(repl, text)


def json_ld_home(site: dict, cases: list[dict]) -> str:
    business = {
        "@type": "HomeAndConstructionBusiness",
        "@id": abs_url(site, "") + "#business",
        "name": site["companyName"],
        "url": site["mainSite"],
        "logo": abs_url(site, site["logo"]),
        "image": abs_url(site, site["ogImage"]),
        "telephone": site["phone"],
        "address": {
            "@type": "PostalAddress",
            "addressLocality": site["city"],
            "addressRegion": site["region"],
            "addressCountry": site["country"],
        },
        "areaServed": site["city"],
        "sameAs": [site["vk"], site["telegramChannel"], site["twoGis"]],
    }
    item_list = {
        "@type": "ItemList",
        "@id": abs_url(site, "") + "#cases",
        "name": "Реализованные ремонты",
        "numberOfItems": len(cases),
        "itemListElement": [
            {
                "@type": "ListItem",
                "position": i + 1,
                "name": c["title"],
                "url": case_url(site, c["id"]),
            }
            for i, c in enumerate(cases)
        ],
    }
    data = {"@context": "https://schema.org", "@graph": [business, item_list]}
    return json.dumps(data, ensure_ascii=False, indent=2)


JSONLD_BLOCK_RE = re.compile(
    r"(<!-- build:jsonld -->).*?(<!-- /build:jsonld -->)", re.DOTALL
)


def inject_home_jsonld(text: str, site: dict, cases: list[dict]) -> str:
    block = (
        "<!-- build:jsonld -->\n"
        '    <script type="application/ld+json">\n'
        f"{json_ld_home(site, cases)}\n"
        "    </script>\n"
        "    <!-- /build:jsonld -->"
    )
    if JSONLD_BLOCK_RE.search(text):
        return JSONLD_BLOCK_RE.sub(lambda _: block, text)
    return text


