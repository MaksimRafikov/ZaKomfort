def build_data_js(cases: list[dict]) -> str:
    public = []
    for c in cases:
        entry = {k: v for k, v in c.items() if k != "order"}
        # Derived responsive-image fields for the catalog cards (js/catalog.js).
        entry["coverSrcset"] = image_srcset(c["cover"], webp=False)
        entry["coverWebpSrcset"] = image_srcset(c["cover"], webp=True)
        public.append(entry)
    payload = json.dumps(public, ensure_ascii=False, indent=2)
    return (
        f"// {GENERATED_NOTE}\n"
        "// Source of truth: content/cases/*.json. Edit those files, then run the build.\n"
        f"const CASES = {payload};\n\n"
        "/** Уникальные ЖК из базы */\n"
        "function getComplexes() {\n"
        "  const set = new Set(CASES.map((c) => c.complex));\n"
        "  return Array.from(set).sort();\n"
        "}\n"
    )


