def format_duration(seconds: object) -> str:
    """Mirror of formatDuration in js/media-utils.js (m:ss)."""
    if not isinstance(seconds, (int, float)) or seconds <= 0:
        return ""
    total = int(seconds)
    return f"{total // 60}:{total % 60:02d}"


def tip_asset_date(tip: dict) -> str:
    video = tip.get("video") or {}
    file_url = video.get("fileUrl")
    if isinstance(file_url, str) and file_url:
        return file_date(ROOT / file_url)
    return file_date(TIPS_DATA_JS)


