def today_iso() -> str:
    return dt.date.today().isoformat()


@lru_cache(maxsize=None)
def git_commit_date(rel: str) -> str | None:
    """Date (YYYY-MM-DD) of the last commit touching the file, if any."""
    try:
        out = subprocess.run(
            ["git", "log", "-1", "--format=%cs", "--", rel],
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=15,
            check=False,
        )
        value = out.stdout.strip()
        return value or None
    except (OSError, subprocess.SubprocessError):
        return None


def file_date(path: Path) -> str:
    """Real content date: last git commit, else mtime (uncommitted files)."""
    if path.is_file():
        rel = path.relative_to(ROOT).as_posix()
        committed = git_commit_date(rel)
        if committed:
            return committed
        return dt.date.fromtimestamp(path.stat().st_mtime).isoformat()
    return today_iso()


